// JTAG signals
// NOTE: THIS ASSUMES f(tck) <= f(CLK)
wire [27:0] O_fabric, I_fabric, T_fabric;
wire jtag_programming;
wire [FrameBitsPerRow-1:0] jtag_SelfWriteData;
wire jtag_SelfWriteStrobe;
reg  prev_jtag_SelfWriteStrobe, jtag_WriteStrobe_posedge;
always @ (posedge CLK) begin
    prev_jtag_SelfWriteStrobe <= jtag_SelfWriteStrobe;
    if (prev_jtag_SelfWriteStrobe == 1'b0 && jtag_SelfWriteStrobe == 1'b1) jtag_WriteStrobe_posedge <= 1'b1;
    else jtag_WriteStrobe_posedge <= 1'b0; 
end


